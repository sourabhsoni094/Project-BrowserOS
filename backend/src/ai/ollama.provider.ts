import { AIProvider, ChatCompletionOptions } from './provider.interface.js';

export class OllamaProvider implements AIProvider {
  name = 'ollama';

  async listModels(baseUrl = 'http://localhost:11434'): Promise<string[]> {
    try {
      const response = await fetch(`${baseUrl}/api/tags`, {
        method: 'GET',
        headers: { 'Content-Type': 'application/json' },
        signal: AbortSignal.timeout(2000), // 2s quick timeout
      });

      if (!response.ok) {
        return [];
      }

      const data = (await response.json()) as { models?: { name: string }[] };
      if (data.models && Array.isArray(data.models) && data.models.length > 0) {
        return data.models.map((m) => m.name);
      }
      return [];
    } catch {
      // Ollama not reachable, return empty array so UI knows it is offline
      return [];
    }
  }

  async chat(options: ChatCompletionOptions, baseUrl = 'http://localhost:11434'): Promise<string> {
    try {
      const messages = [...options.messages];
      if (options.systemPrompt) {
        messages.unshift({ role: 'system', content: options.systemPrompt });
      }

      const response = await fetch(`${baseUrl}/api/chat`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        signal: AbortSignal.timeout(15000), // 15s timeout
        body: JSON.stringify({
          model: options.model || 'llama3',
          messages: messages.map((m) => ({ role: m.role, content: m.content })),
          stream: false,
          options: {
            temperature: options.temperature || 0.7,
          },
        }),
      });

      if (!response.ok) {
        const errorText = await response.text();
        throw new Error(`Ollama returned status ${response.status}: ${errorText}`);
      }

      const data = (await response.json()) as { message?: { content: string } };
      return data.message?.content || 'No response generated by model.';
    } catch (err: any) {
      if (
        err.name === 'TimeoutError' ||
        err.message?.includes('ECONNREFUSED') ||
        err.message?.includes('fetch failed')
      ) {
        throw new Error(
          `Could not connect to local Ollama runtime at ${baseUrl}.\nPlease ensure Ollama is installed and running (e.g. run "ollama run llama3").`
        );
      }
      throw err;
    }
  }
}

export const ollamaProvider = new OllamaProvider();
